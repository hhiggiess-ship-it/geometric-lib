import math


def area(r):
    """
    Функция вычисления площади с заданным радиусом r
    
    принимает параметр: r (int): радиус
    возвращает: площадь (float)
    """
    return math.pi * r * r


def perimeter(r):
    """
    Функция вычисления периметра с заданным радиусом r
    
    принимает параметр: r (int): радиус
    возвращает: периметр (float)
    """
    return 2 * math.pi * r

